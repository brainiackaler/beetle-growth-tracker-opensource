export function getDeviceLanguage() {
  if (typeof navigator === 'undefined') return 'zh-CN';
  return navigator.languages?.[0] || navigator.language || 'zh-CN';
}

export function normalizeLanguage(language) {
  const normalized = String(language || '').replace('_', '-').toLowerCase();
  if (normalized.startsWith('zh')) {
    return /(?:hant|tw|hk|mo)/.test(normalized) ? 'zh-TW' : 'zh-CN';
  }
  return 'en';
}

export function resolveLanguage(mode) {
  return mode === 'system' ? normalizeLanguage(getDeviceLanguage()) : normalizeLanguage(mode);
}

export function getInitialMode() {
  if (typeof localStorage === 'undefined') return 'system';
  const stored = localStorage.getItem(LANGUAGE_STORAGE_KEY);
  return LANGUAGE_MODES.includes(stored) ? stored : 'system';
}

function applyTraditionalPhrases(text) {
  let result = text;
  Object.entries(TRADITIONAL_PHRASES)
    .sort(([left], [right]) => right.length - left.length)
    .forEach(([source, translation]) => {
      result = result.split(source).join(translation);
    });
  return Array.from(result, character => TRADITIONAL_CHARACTERS[character] || character).join('');
}

const EN_REPLACEMENTS = Object.entries(EN_TRANSLATIONS)
  .filter(([source]) => source.length > 1)
  .sort(([left], [right]) => right.length - left.length);

function applyEnglishPhrases(text) {
  if (EN_TRANSLATIONS[text]) return EN_TRANSLATIONS[text];

  let result = text;
  EN_REPLACEMENTS.forEach(([source, translation]) => {
    result = result.split(source).join(translation);
  });
  return result;
}

function interpolate(text, values) {
  return Object.entries(values || {}).reduce(
    (result, [key, value]) => result.split(`{${key}}`).join(String(value)),
    text
  );
}

export function translate(source, values) {
  if (source === null || source === undefined) return '';
  const template = String(source);
  const text = interpolate(template, values);
  if (activeLanguage === 'zh-CN') return text;
  if (activeLanguage === 'zh-TW') {
    if (template === '只') return '隻';
    return applyTraditionalPhrases(text);
  }
  if (EN_TRANSLATIONS[template]) return interpolate(EN_TRANSLATIONS[template], values);
  return applyEnglishPhrases(text);
}

export function translateValue(source) {
  if (source === null || source === undefined) return '';
  const text = String(source);
  if (activeLanguage === 'zh-CN') return text;
  if (activeLanguage === 'zh-TW') return applyTraditionalPhrases(text);
  return EN_TRANSLATIONS[text] || text;
}

export function setActiveLanguage(language) {
  activeLanguage = normalizeLanguage(language);
}

